create table if not exists public.birth_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  calendar_type text not null check (calendar_type in ('solar', 'lunar')),
  is_leap_month boolean not null default false,
  birth_date date not null,
  birth_time time,
  birth_time_precision text not null check (birth_time_precision in ('exact', 'approximate', 'unknown')),
  birth_country_code char(2) not null check (birth_country_code ~ '^[A-Z]{2}$'),
  birth_city varchar(80) not null,
  created_at timestamptz not null default now(),
