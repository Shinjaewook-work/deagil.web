create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nickname varchar(30),
  account_status text not null default 'active' check (account_status in ('active', 'suspended')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_active_at timestamptz not null default now(),
  check (nickname is null or (length(nickname) <= 30 and nickname !~ '[\u0000-\u001F\u007F]'))
);

create table if not exists public.user_entry_records (
  user_id uuid primary key references auth.users(id) on delete cascade,
  age_14_plus_attested_at timestamptz not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.legal_documents (
  id uuid primary key default gen_random_uuid(),
  document_type text not null,
  version text not null,
  status text not null check (status in ('draft', 'active', 'retired')),
  title text not null,
  public_url text not null,
  interaction text not null check (interaction in ('acceptance_required', 'consent_required', 'notice_only', 'link_only')),
  required_for_registration boolean not null default false,
  required_for_ai boolean not null default false,
  withdrawable boolean not null default false,
  provider_set_version text,
  content_sha256 text,
  effective_at timestamptz,
  created_at timestamptz not null default now(),
  unique (document_type, version),
  check (public_url ~ '^https://'),
  check (not withdrawable or interaction = 'consent_required')
);

create table if not exists public.user_consent_events (
