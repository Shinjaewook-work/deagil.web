create or replace function public.get_current_fortune_date(now_timestamptz timestamptz default now())
returns date language sql stable as $$
  select ((now_timestamptz at time zone 'Asia/Seoul') - interval '4 hours')::date;
$$;

create or replace function public.is_fortune_transition_window(now_timestamptz timestamptz default now())
returns boolean language sql stable as $$
  select ((now_timestamptz at time zone 'Asia/Seoul')::time >= time '03:55'
    and (now_timestamptz at time zone 'Asia/Seoul')::time < time '04:00');
$$;

create or replace function public.get_fortune_day_expires_at(fortune_day date)
returns timestamptz language sql immutable as $$
  select ((fortune_day + 1)::timestamp + time '03:59:59.999999') at time zone 'Asia/Seoul';
$$;

create or replace function public.get_my_app_state()
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare
  current_user_id uuid := auth.uid();
  now_value timestamptz := now();
  current_day date := public.get_current_fortune_date(now_value);
  current_session public.daily_fortune_sessions%rowtype;
  current_profile public.profiles%rowtype;
  required_registration_count integer;
  accepted_registration_count integer;
  gate_value text := 'NONE';
  state_value text := 'NO_SESSION';
  readable boolean := false;
begin
  if current_user_id is null then
    return jsonb_build_object('api_contract_version', 1, 'server_now', now_value, 'gate', 'REGISTRATION_REQUIRED', 'fortune_state', 'NO_SESSION');
  end if;

  select * into current_profile from public.profiles where id = current_user_id;
  if current_profile.account_status = 'suspended' then gate_value := 'ACCOUNT_SUSPENDED';
  elsif not exists (select 1 from public.user_entry_records where user_id = current_user_id) then gate_value := 'REGISTRATION_REQUIRED';
  else
    select count(*) into required_registration_count from public.legal_documents where status = 'active' and required_for_registration;
    select count(*) into accepted_registration_count
      from public.legal_documents d
      where d.status = 'active' and d.required_for_registration
        and exists (select 1 from public.user_consent_events e where e.user_id = current_user_id and e.legal_document_id = d.id and e.action = 'accepted'
          and e.event_at = (select max(e2.event_at) from public.user_consent_events e2 where e2.user_id = current_user_id and e2.legal_document_id = d.id));
    if accepted_registration_count < required_registration_count then gate_value := 'CONSENT_UPDATE_REQUIRED'; end if;
  end if;

  select * into current_session from public.daily_fortune_sessions where user_id = current_user_id and fortune_date = current_day;
  if current_session.id is not null then
    readable := current_session.entitlement_status <> 'none' and current_session.generation_status = 'ready'
      and current_session.fortune_payload is not null and now_value < current_session.expires_at;
    if public.is_fortune_transition_window(now_value) then state_value := 'TRANSITION_WINDOW';
    elsif readable then state_value := 'UNLOCKED';
    elsif current_session.generation_status = 'generating' then state_value := 'GENERATING';
    elsif current_session.generation_status = 'recovery_pending' then state_value := 'RECOVERY_PENDING';
    elsif current_session.generation_status = 'failed' then state_value := 'FAILED';
    elsif current_session.generation_status = 'ready' then state_value := 'READY_LOCKED';
    else state_value := 'LOCKED'; end if;
  elsif public.is_fortune_transition_window(now_value) then state_value := 'TRANSITION_WINDOW'; end if;

  return jsonb_build_object(
    'api_contract_version', 1, 'server_now', now_value, 'gate', gate_value, 'fortune_state', state_value,
    'fortune_date', current_day, 'expires_at', current_session.expires_at,
    'birth_profile_exists', exists(select 1 from public.birth_profiles where user_id = current_user_id),
    'available_pass_count', (select count(*) from public.fortune_passes where user_id = current_user_id and status = 'available' and current_day between valid_from_fortune_date and expires_after_fortune_date),
    'active_pass_count', (select count(*) from public.fortune_passes where user_id = current_user_id and status in ('available', 'reserved')),
    'can_prepare_rewarded_ad', gate_value = 'NONE' and not readable and not public.is_fortune_transition_window(now_value),
    'can_use_pass', gate_value = 'NONE' and not readable and not public.is_fortune_transition_window(now_value)
      and exists(select 1 from public.fortune_passes where user_id = current_user_id and status = 'available' and current_day between valid_from_fortune_date and expires_after_fortune_date),
    'next_retry_at', current_session.next_retry_at,
    'fortune_payload', case when readable then current_session.fortune_payload else null end
  );
end;
$$;

create or replace function public.upsert_my_birth_profile(payload jsonb)
returns public.birth_profiles language plpgsql security definer set search_path = public, pg_temp as $$
declare result public.birth_profiles; city_value text;
begin
  if auth.uid() is null then raise exception 'UNAUTHENTICATED'; end if;
  city_value := btrim(normalize(payload->>'birth_city', NFC));
  if length(city_value) = 0 or length(city_value) > 80 or city_value ~ '[\u0000-\u001F\u007F]' or city_value ~* '(https?://|www\.)' or city_value ~ '[\r\n]' then raise exception 'INVALID_BIRTH_CITY'; end if;
  if payload->>'calendar_type' not in ('solar', 'lunar') then raise exception 'INVALID_CALENDAR_TYPE'; end if;
  if payload->>'birth_time_precision' = 'unknown' then payload := jsonb_set(payload, '{birth_time}', 'null'::jsonb); end if;
  if payload->>'birth_time_precision' <> 'unknown' and payload->>'birth_time' is null then raise exception 'BIRTH_TIME_REQUIRED'; end if;
  insert into public.birth_profiles(user_id, calendar_type, is_leap_month, birth_date, birth_time, birth_time_precision, birth_country_code, birth_city)
  values (auth.uid(), payload->>'calendar_type', coalesce((payload->>'is_leap_month')::boolean, false), (payload->>'birth_date')::date, (payload->>'birth_time')::time, payload->>'birth_time_precision', upper(payload->>'birth_country_code'), city_value)
  on conflict (user_id) do update set calendar_type = excluded.calendar_type, is_leap_month = excluded.is_leap_month, birth_date = excluded.birth_date, birth_time = excluded.birth_time, birth_time_precision = excluded.birth_time_precision, birth_country_code = excluded.birth_country_code, birth_city = excluded.birth_city, updated_at = now()
  returning * into result;
  return result;
end;
$$;

create or replace function public.set_my_profile(nickname_value text)
returns public.profiles language plpgsql security definer set search_path = public, pg_temp as $$
declare result public.profiles; clean_name text;
begin
  if auth.uid() is null then raise exception 'UNAUTHENTICATED'; end if;
  clean_name := nullif(btrim(normalize(nickname_value, NFC)), '');
  if clean_name is not null and (length(clean_name) > 30 or clean_name ~ '[\u0000-\u001F\u007F]' or clean_name ~ '[\r\n]') then raise exception 'INVALID_NICKNAME'; end if;
  insert into public.profiles(id, nickname) values (auth.uid(), clean_name)
  on conflict (id) do update set nickname = excluded.nickname, updated_at = now(), last_active_at = now()
  returning * into result;
  return result;
end;
$$;

create or replace function public.set_my_privacy_preferences(analytics_enabled_value boolean)
returns public.privacy_preferences language plpgsql security definer set search_path = public, pg_temp as $$
declare result public.privacy_preferences;
begin
  if auth.uid() is null then raise exception 'UNAUTHENTICATED'; end if;
  insert into public.privacy_preferences(user_id, analytics_enabled) values (auth.uid(), coalesce(analytics_enabled_value, false))
  on conflict (user_id) do update set analytics_enabled = excluded.analytics_enabled, updated_at = now()
  returning * into result;
  return result;
end;
$$;

create or replace function public.set_my_notification_preferences(enabled_value boolean, notification_time_value time, prompt_status_value text)
returns public.notification_preferences language plpgsql security definer set search_path = public, pg_temp as $$
declare result public.notification_preferences;
begin
  if auth.uid() is null then raise exception 'UNAUTHENTICATED'; end if;
  if prompt_status_value not in ('never_asked', 'enabled', 'declined') then raise exception 'INVALID_PROMPT_STATUS'; end if;
  insert into public.notification_preferences(user_id, enabled, notification_time, prompt_status)
  values (auth.uid(), coalesce(enabled_value, false), coalesce(notification_time_value, time '08:00'), prompt_status_value)
  on conflict (user_id) do update set enabled = excluded.enabled, notification_time = excluded.notification_time, prompt_status = excluded.prompt_status, updated_at = now()
  returning * into result;
  return result;
end;
$$;

create or replace function public.record_my_consent_event(document_id uuid, action_value text)
returns public.user_consent_events language plpgsql security definer set search_path = public, pg_temp as $$
declare document_row public.legal_documents; result public.user_consent_events;
begin
  if auth.uid() is null then raise exception 'UNAUTHENTICATED'; end if;
  select * into document_row from public.legal_documents where id = document_id and status = 'active';
  if document_row.id is null then raise exception 'LEGAL_DOCUMENT_NOT_ACTIVE'; end if;
  if action_value not in ('accepted', 'withdrawn') then raise exception 'INVALID_CONSENT_ACTION'; end if;
  if action_value = 'withdrawn' and not document_row.withdrawable then raise exception 'CONSENT_NOT_WITHDRAWABLE'; end if;
  insert into public.user_consent_events(user_id, legal_document_id, action, source)
  values (auth.uid(), document_row.id, action_value, 'app') returning * into result;
  return result;
end;
$$;

